create or replace function public.notify_post_owner_on_comment() returns trigger language plpgsql security definer set search_path = public as $$
declare owner_id uuid; item_title text; begin
  select user_id, title into owner_id, item_title from public.posts where id = new.post_id;
  if owner_id is not null and owner_id <> new.user_id then
    insert into public.notifications(user_id, actor_id, post_id, body)
      values(owner_id, new.user_id, new.post_id, coalesce((select username from public.profiles where id=new.user_id),'Someone') || ' replied to “' || item_title || '”.');
  end if;
  return new;
end $$;
drop trigger if exists comment_creates_notification on public.comments;
create trigger comment_creates_notification after insert on public.comments for each row execute function public.notify_post_owner_on_comment();

