-- Run in the Supabase SQL editor. Existing posts/comments tables are extended safely.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null default 'Reef explorer',
  bio text not null default '',
  avatar_url text,
  created_at timestamptz not null default now()
);
create or replace function public.create_profile_for_new_user() returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(id, username, bio) values(new.id, coalesce(new.raw_user_meta_data->>'username','Reef explorer'), 'Exploring the big blue.') on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists auth_user_profile on auth.users;
create trigger auth_user_profile after insert on auth.users for each row execute function public.create_profile_for_new_user();

-- Bootstrap these tables for a fresh Supabase project as well as extending
-- installations that already have the starter app tables.
create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  location text not null,
  type text not null default 'Lost',
  created_at timestamptz not null default now(),
  user_id uuid references public.profiles(id) on delete cascade,
  image_url text,
  returned boolean not null default false
);
create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid references public.profiles(id) on delete cascade,
  parent_id bigint references public.comments(id) on delete cascade,
  body text not null,
  created_at timestamptz not null default now()
);
alter table public.posts add column if not exists user_id uuid references public.profiles(id) on delete cascade;
alter table public.posts add column if not exists image_url text;
alter table public.posts add column if not exists returned boolean not null default false;
alter table public.comments add column if not exists user_id uuid references public.profiles(id) on delete cascade;

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  actor_id uuid references auth.users(id) on delete set null,
  post_id text,
  body text not null,
  read boolean not null default false,
  created_at timestamptz not null default now()
);
do $$ declare id_type text; begin
  select format_type(a.atttypid, a.atttypmod) into id_type from pg_attribute a where a.attrelid='public.comments'::regclass and a.attname='id' and not a.attisdropped;
  if id_type is not null then execute format('alter table public.comments add column if not exists parent_id %s references public.comments(id) on delete cascade', id_type); end if;
  select format_type(a.atttypid, a.atttypmod) into id_type from pg_attribute a where a.attrelid='public.posts'::regclass and a.attname='id' and not a.attisdropped;
  if id_type is not null then
    execute format('alter table public.notifications alter column post_id type %s using null', id_type);
    execute 'alter table public.notifications drop constraint if exists notifications_post_id_fkey';
    execute 'alter table public.notifications add constraint notifications_post_id_fkey foreign key (post_id) references public.posts(id) on delete cascade';
  end if;
end $$;

alter table public.profiles enable row level security;
alter table public.posts enable row level security;
alter table public.comments enable row level security;
alter table public.notifications enable row level security;

